#!/usr/bin/env node
/**
 * Generates src/renderer/shared/icons.js from Drift Glyphs (scripts/glyphs.cjs),
 * the interface icon set drawn for Drift. No third-party icon library or React
 * is needed: the glyphs are plain SVG fragments on a 24 x 24 grid.
 *
 * The output is committed, so `npm start` and packaged builds need no build step.
 *
 *   npm run icons:build
 *
 * To add an icon: add `name: '<path .../>'` to scripts/glyphs.cjs, rebuild, then
 * use <svg data-fa="name"></svg> in markup (or window.fa('name') in script).
 */
const fs = require('fs');
const path = require('path');
const glyphs = require('./glyphs.cjs');

const icons = {};
for (const [name, inner] of Object.entries(glyphs)) {
  if (typeof inner !== 'string' || !inner.trim().startsWith('<')) throw new Error(`Glyph "${name}" is not SVG markup`);
  icons[name] = ['0 0 24 24', inner];
}

const body = Object.entries(icons).map(([n, [vb, svg]]) => `    ${n}: [${JSON.stringify(vb)}, ${JSON.stringify(svg)}]`).join(',\n');
const out = `/* GENERATED by scripts/build_icons.cjs from scripts/glyphs.cjs. Do not edit; run \`npm run icons:build\`.
 * Icons: Drift Glyphs, drawn for Drift (MIT, same as the app). */
(function () {
  'use strict';
  var ICONS = {
${body}
  };

  function markup(name, cls) {
    var def = ICONS[name];
    if (!def) return '';
    return '<svg class="fa' + (cls ? ' ' + cls : '') + '" viewBox="' + def[0] + '" aria-hidden="true" focusable="false">' + def[1] + '</svg>';
  }

  // <svg data-fa="name"></svg> placeholders are filled in place, so ids, classes
  // and CSS targeting the element keep working. This runs for static markup and,
  // through the observer below, for anything the UI renders later.
  function hydrate(root) {
    var nodes = root.querySelectorAll ? root.querySelectorAll('svg[data-fa]:not(.fa)') : [];
    if (root.matches && root.matches('svg[data-fa]:not(.fa)')) fill(root);
    for (var i = 0; i < nodes.length; i++) fill(nodes[i]);
  }
  function fill(node) {
    var def = ICONS[node.getAttribute('data-fa')];
    if (!def) return;
    node.setAttribute('viewBox', def[0]);
    node.setAttribute('aria-hidden', 'true');
    node.setAttribute('focusable', 'false');
    node.classList.add('fa');
    node.innerHTML = def[1];
  }

  window.fa = markup;
  window.DRIFT_ICONS = ICONS;
  hydrate(document);
  new MutationObserver(function (records) {
    for (var i = 0; i < records.length; i++) {
      var added = records[i].addedNodes;
      for (var j = 0; j < added.length; j++) if (added[j].nodeType === 1) hydrate(added[j]);
    }
  }).observe(document.documentElement, { childList: true, subtree: true });
})();
`;
const target = path.join(__dirname, '..', 'src', 'renderer', 'shared', 'icons.js');
fs.writeFileSync(target, out);
console.log(`Wrote ${Object.keys(icons).length} icons to ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(1)} KB)`);
